    return LessonSentence(
      id: 'sent_${_baseSentencesLessons.length + index + 1}',
      sentence:
          '${subject.arabic} ${_sentenceActionForForm(action: action, form: subject.form)}',
      meaning: action.meaning,
      meaningEn:
          '${subject.english} ${_sentenceMeaningEnForForm(action: action, form: subject.form)}',
      usage: action.usage,
    );
  },
);

