String _sentenceActionForForm({
  required ({
    String feminine,
    String first,
    String masculine,
    String plural,
    String meaning,
    String enFirst,
    String enPlural,
    String enThird,
    String usage,
  })
  action,
  required String form,
}) {
  return switch (form) {
    'first' => action.first,
    'masculine' => action.masculine,
    'feminine' => action.feminine,
    _ => action.plural,
  };
}

String _sentenceMeaningEnForForm({
  required ({
    String feminine,
    String first,
    String masculine,
    String plural,
    String meaning,
    String enFirst,
    String enPlural,
    String enThird,
    String usage,
  })
  action,
  required String form,
}) {
  return switch (form) {
    'first' => action.enFirst,
    'masculine' || 'feminine' => action.enThird,
    _ => action.enPlural,
  };
}

