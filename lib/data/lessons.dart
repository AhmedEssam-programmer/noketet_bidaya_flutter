class LessonSound {
  const LessonSound({
    required this.id,
    required this.letter,
    required this.name,
    required this.examples,
    required this.emoji,
  });

  final String id;
  final String letter;
  final String name;
  final List<String> examples;
  final String emoji;
}

class LessonLetter {
  const LessonLetter({
    required this.id,
    required this.letter,
    required this.name,
    required this.initial,
    required this.middle,
    required this.finalForm,
    required this.words,
  });

  final String id;
  final String letter;
  final String name;
  final String initial;
  final String middle;
  final String finalForm;
  final List<String> words;
}

class LessonWord {
  const LessonWord({
    required this.id,
    required this.word,
    required this.meaning,
    required this.meaningEn,
    required this.category,
    required this.emoji,
  });

  final String id;
  final String word;
  final String meaning;
  final String meaningEn;
  final String category;
  final String emoji;
}

class LessonSentence {
  const LessonSentence({
    required this.id,
    required this.sentence,
    required this.meaning,
    required this.meaningEn,
    required this.usage,
  });

  final String id;
  final String sentence;
  final String meaning;
  final String meaningEn;
  final String usage;
}

